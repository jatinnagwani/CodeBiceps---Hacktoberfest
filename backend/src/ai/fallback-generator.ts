import {
  PullRequestPayload,
  HeuristicFinding,
  Verdict,
  Confidence,
  TriageResult,
  EvidenceItem,
  SuggestedComment,
} from '@proof/shared';

/**
 * Deterministically generates a triage result when Ollama local AI is offline or unreachable.
 * Never pretends to be AI output; clearly flags the result as HEURISTICS_FALLBACK.
 */
export function generateHeuristicsFallback(
  pr: PullRequestPayload,
  heuristicFindings: HeuristicFinding[],
  heuristicScore: number,
  executionTimeMs: number
): TriageResult {
  const whitespaceFinding = heuristicFindings.find(f => f.id === 'whitespace-check');
  const emptyDiffFinding = heuristicFindings.find(f => f.id === 'empty-diff-check');
  const testFinding = heuristicFindings.find(f => f.id === 'test-coverage-check');
  const issueFinding = heuristicFindings.find(f => f.id === 'linked-issue-check');
  const templateFinding = heuristicFindings.find(f => f.id === 'template-check');

  let verdict: Verdict;
  let confidence: Confidence;
  let summary: string;

  // Determine verdict deterministically from heuristic findings
  if (whitespaceFinding && !whitespaceFinding.passed && whitespaceFinding.severity === 'CRITICAL') {
    verdict = 'LIKELY_SPAM';
    confidence = 'HIGH';
    summary = 'Heuristic analysis identified this PR as likely spam due to changes consisting solely of whitespace or trivial formatting adjustments.';
  } else if (emptyDiffFinding && !emptyDiffFinding.passed && emptyDiffFinding.severity === 'CRITICAL') {
    verdict = 'LIKELY_SPAM';
    confidence = 'HIGH';
    summary = 'Heuristic analysis identified this PR as likely spam or low-effort due to an empty diff with no substantive additions or deletions.';
  } else if (heuristicScore >= 70 && testFinding?.passed) {
    verdict = 'GENUINE';
    confidence = heuristicScore >= 80 ? 'HIGH' : 'MEDIUM';
    summary = 'Heuristic analysis indicates a well-structured, substantive contribution with active test coverage and context.';
  } else {
    verdict = 'NEEDS_WORK';
    confidence = 'MEDIUM';
    summary = 'Heuristic analysis suggests a legitimate attempt that requires further refinement, tests, or documentation before review.';
  }

  // Convert heuristic findings to verifiable evidence items
  const evidence: EvidenceItem[] = heuristicFindings.map(h => ({
    id: `ev-${h.id}`,
    type: 'HEURISTIC',
    severity: h.passed ? 'POSITIVE' : (h.severity === 'CRITICAL' ? 'CONCERN' : 'NEUTRAL'),
    description: h.evidence,
    file: pr.filesChanged[0]?.filename,
  }));

  // Build polite suggested comment based on verdict
  let suggestedComment: SuggestedComment;

  if (verdict === 'GENUINE') {
    suggestedComment = {
      greeting: `Hi @${pr.author}! 👋`,
      summary: `Thank you for taking the time to submit this pull request: "${pr.title}".`,
      actionablePoints: [
        'Great job including test coverage alongside your code changes.',
        pr.linkedIssue ? `Properly linked to issue ${pr.linkedIssue}.` : 'Clear description provided.',
        'Our maintainers will review the implementation details shortly.',
      ],
      closing: 'Thank you for contributing to open source!',
      tone: 'ENCOURAGING',
      isEdited: false,
      markdown: `Hi @${pr.author}! 👋\n\nThank you for submitting this pull request! Your contribution looks well-structured and includes appropriate tests. A maintainer will conduct a detailed code review soon.\n\n*Generated by PRoof (Heuristics-Only Mode)*`,
    };
  } else if (verdict === 'NEEDS_WORK') {
    const missingItems: string[] = [];
    if (!testFinding?.passed) missingItems.push('Add unit or integration tests to verify your implementation.');
    if (!issueFinding?.passed) missingItems.push('Link the related issue (e.g. `Closes #...`) or explain the motivation in the PR description.');
    if (!templateFinding?.passed) missingItems.push('Complete the PR template checklist and provide additional reproduction or context details.');

    suggestedComment = {
      greeting: `Hi @${pr.author}! 👋`,
      summary: `Thank you for your interest in contributing to our project with "${pr.title}".`,
      actionablePoints: missingItems.length > 0 ? missingItems : ['Please review the project contributing guidelines for required checks.'],
      closing: 'Please update your branch with these improvements so we can proceed with review.',
      tone: 'CONSTRUCTIVE_GUIDANCE',
      isEdited: false,
      markdown: `Hi @${pr.author}! 👋\n\nThank you for your contribution! We appreciate your effort on this PR. Before we can merge this, could you please address the following points?\n\n${missingItems.map(m => `- ${m}`).join('\n')}\n\nLet us know once you've pushed updates and we'll gladly review again!\n\n*Generated by PRoof (Heuristics-Only Mode)*`,
    };
  } else {
    suggestedComment = {
      greeting: `Hello @${pr.author},`,
      summary: 'Thank you for your interest in our project.',
      actionablePoints: [
        'Our automated checks noticed this PR contains only whitespace, indentation, or cosmetic line adjustments.',
        'During Hacktoberfest, we require contributions to provide substantive code improvements, bugfixes, or meaningful documentation.',
        'Please check our `CONTRIBUTING.md` and open issues tagged with `good first issue` for impactful tasks to work on.',
      ],
      closing: 'We encourage you to tackle one of our open issues if you would like to contribute meaningfully.',
      tone: 'POLITE_CAUTION',
      isEdited: false,
      markdown: `Hello @${pr.author},\n\nThank you for your pull request. However, our checks indicate that the submitted changes consist solely of whitespace, formatting, or minor cosmetic adjustments without substantive changes to the codebase.\n\nTo keep our review queue manageable and maintain high repository standards, we kindly request that contributors focus on meaningful bug fixes or feature requests. Please take a look at our open issues labeled \`good first issue\` if you'd like to make a genuine impact!\n\n*Generated by PRoof (Heuristics-Only Mode)*`,
    };
  }

  return {
    prId: pr.id,
    verdict,
    confidence,
    engine: 'HEURISTICS_FALLBACK',
    engineDetails: {
      ollamaAvailable: false,
      modelName: 'None (Deterministic Rules)',
      executionTimeMs,
      isFallback: true,
      notes: 'Ollama is offline or unreachable. Verdict generated deterministically using rule-based heuristics.',
    },
    summary,
    heuristicFindings,
    evidence,
    suggestedComment,
    metadata: {
      analyzedAt: new Date().toISOString(),
      rulesTriggered: heuristicFindings.filter(f => !f.passed).map(f => f.id),
      heuristicScore,
    },
  };
}
